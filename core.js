  const KEY = 'revolve3d.lang';
  let lang = 'en';
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === 'en' || saved === 'bm') lang = saved;
  } catch (e) { /* storage unavailable: keep English */ }

  const listeners = [];

  function t(key, vars) {
    let s = (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.en[key] || key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
    return s;
  }

  // Pick the right language from a bilingual object { en, bm }; plain strings pass through.
  function pick(o) {
    return o && typeof o === 'object' ? (o[lang] || o.en) : o;
  }

  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    scope.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
    scope.querySelectorAll('[data-i18n-aria]').forEach(el => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
    document.documentElement.lang = lang === 'bm' ? 'ms' : 'en';
    document.querySelectorAll('[data-lang]').forEach(b => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
  }

  function setLang(next) {
    if (next !== 'en' && next !== 'bm') return;
    lang = next;
    try { localStorage.setItem(KEY, next); } catch (e) { /* ignore */ }
    apply();
    listeners.forEach(fn => fn(lang));
  }

  // Small DOM builder: h('p', { class: 'x', onclick: fn }, 'text', childNode)
  function h(tag, attrs, ...kids) {
    const el = document.createElement(tag);
    Object.entries(attrs || {}).forEach(([k, v]) => {
      if (v === null || v === undefined || v === false) return;
      if (k === 'class') el.className = v;
      else if (k.startsWith('on')) el.addEventListener(k.slice(2), v);
      else if (k === 'html') el.innerHTML = v;
      else if (v === true) el.setAttribute(k, '');
      else el.setAttribute(k, String(v));
    });
    kids.flat(Infinity).forEach(c => {
      if (c === null || c === undefined || c === false) return;
      el.append(c instanceof Node ? c : document.createTextNode(String(c)));
    });
    return el;
  }

  RV.i18n = {
    t,
    pick,
    apply,
    setLang,
    onChange: fn => listeners.push(fn),
    get lang() { return lang; }
  };
  RV.dom = { h };
